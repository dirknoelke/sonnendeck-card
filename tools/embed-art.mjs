// Turns art/*.webp into src/art.ts, so the card stays one self-contained file.
// art.ts is a plain script (no export): tools/bundle.mjs joins it in front of the card.
// Run after changing a picture:  node tools/embed-art.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const dir = new URL('../art/', import.meta.url);
const names = readdirSync(dir).filter((f) => f.endsWith('.webp')).sort();
let out = `/* generated by tools/embed-art.mjs from art/*.webp: do not edit */\n\nconst ART: Record<string, string> = {\n`;
for (const f of names) {
  const b64 = readFileSync(new URL(f, dir)).toString('base64');
  out += `  '${f.replace('.webp', '')}': 'data:image/webp;base64,${b64}',\n`;
}
out += `};\n`;
writeFileSync(new URL('../src/art.ts', import.meta.url), out);
console.log(`${names.length} pictures, ${(out.length / 1024).toFixed(0)} KB`);
